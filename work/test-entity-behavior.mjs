import assert from 'node:assert/strict';
import {createEntityBehavior,normalizeBehavior} from './entities/behaviors.mjs';
import {normalizePrefab} from './tile-model.mjs';
import {placeEntity} from './entity-model.mjs';
const input={scriptId:'replace-cell',parameters:{nested:[[1]]},state:{count:2}};
const behavior=createEntityBehavior(input);input.parameters.nested[0][0]=9;
assert.equal(behavior.toJSON().parameters.nested[0][0],1);
assert.deepEqual(createEntityBehavior(JSON.parse(JSON.stringify(behavior))).toJSON(),behavior.toJSON());
assert.throws(()=>createEntityBehavior({scriptId:'unregistered'}),/未注册/);
assert.throws(()=>normalizeBehavior({scriptId:'../remote'}),/无效/);
assert.throws(()=>normalizeBehavior({scriptId:'replace-cell',state:{value:Infinity}}),/JSON/);
const prefab=normalizePrefab({version:1,id:'test_ai',name:'测试',BaseEntity:['void_ai'],tile:{height:.2,blocked:false}});
const map={width:3,height:3,tiles:Array.from({length:3},()=>Array(3).fill(null)),foldCells:[]};
assert.ok(placeEntity(map,prefab,prefab.tile,0,0).map.tiles[0][0]);assert.equal(map.tiles[0][0],null);
map.tiles[0][0]={prefabId:'paper_ai',height:.2,blocked:false};const before=JSON.stringify(map);
assert.throws(()=>placeEntity(map,prefab,prefab.tile,0,0),/不允许/);assert.equal(JSON.stringify(map),before);
assert.throws(()=>placeEntity(map,{...prefab,BaseEntity:[]},prefab.tile,1,1),/不允许/);
assert.doesNotThrow(()=>placeEntity(map,{...prefab,BaseEntity:undefined},prefab.tile,0,0));
console.log('PASS: objectified behavior serialization, controlled IDs, explicit bases, empty rejection and atomic legacy-compatible replacement.');
