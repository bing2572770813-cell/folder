import assert from 'node:assert/strict';
import vm from 'node:vm';
import {gameHtml,runtimePrefabs} from './core/game-export.mjs';
const prefabs=[{id:'paper',propertySchema:{height:{tempEditable:true}},components:{surface:{height:.4}},configuration:{permissions:{door:'key'}},static:{entityType:'terrain'},children:[{propertySchema:{},components:{key:{name:'铜'}}}]}];
const before=structuredClone(prefabs),map={name:'</script><script>bad()</script>',spawn:{r:1,c:1,dir:0}};
const html=gameHtml('<!doctype html><div id="viewport"></div><!--APP_SCRIPT-->','window.started=true;', {map,prefabs,assets:{'model/test.fbx':'data:application/octet-stream;base64,AA=='}});
assert.deepEqual(prefabs,before);
assert.equal(runtimePrefabs(prefabs)[0].propertySchema,undefined);
assert.deepEqual(runtimePrefabs(prefabs)[0].components,prefabs[0].components);
assert.deepEqual(runtimePrefabs(prefabs)[0].configuration,prefabs[0].configuration,'custom runtime fields must not be mistaken for authoring metadata');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,2,'HTML names must not inject scripts');
const context={window:{}};vm.runInNewContext(scripts[0][1],context);
assert.equal(context.window.__FOLD_FIELD_GAME_ONLY__,true);
assert.equal(context.window.__FOLD_FIELD_EXPORT_MAP__.name,map.name);
assert.equal(context.window.__FOLD_FIELD_PREFABS__[0].children[0].components.key.name,'铜');
assert.equal(context.window.__FOLD_FIELD_PREFABS__[0].children[0].propertySchema,undefined);
assert.equal(context.window.__FOLD_FIELD_EXPORT_ASSETS__['model/test.fbx'],'data:application/octet-stream;base64,AA==');
assert.throws(()=>gameHtml('', '', {map,prefabs}),/模板/);
const clean=gameHtml('<body><!--APP_SCRIPT--></body>','window.editorCatalog="/*FOLD_FIELD_PLAY_RUNTIME*/";\n/*FOLD_FIELD_PLAY_RUNTIME*/\nwindow.started=true;', {map,prefabs});
assert.equal(clean.includes('window.editorCatalog'),false,'the authoring bootstrap must not be re-embedded');
assert.ok(clean.includes('window.started=true;'));
assert.ok(clean.includes('<body class="game-only">'),'first paint must hide authoring UI before loading the runtime');
console.log('PASS: clean game template embeds immutable runtime prefabs and assets, removes authoring schemas and escapes script data.');
