import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {Box3,Group,Vector3} from 'three';
import {createFbxModelLoader} from './render/fbx-model-loader.mjs';
import {createModelLibrary} from './render/model-library.mjs';
import {createModelView} from './render/model-view.mjs';
const prefab=JSON.parse(await readFile(new URL('../assets/prefab/entity/player_ai.json',import.meta.url)));
assert.equal(prefab.visual?.model,'model/newwitch.fbx');
const library=createModelLibrary({load:createFbxModelLoader({read:async path=>{
 const bytes=await readFile(new URL('../assets/'+path,import.meta.url));
 return bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength);
},url:()=>{throw new Error('player model must be self contained');}})});
const instance=await library.instantiate(prefab.visual),box=new Box3().setFromObject(instance),size=box.getSize(new Vector3()),center=box.getCenter(new Vector3());
assert.ok(size.y>1&&size.y<2,'witch has a visible grid-scale height');
assert.ok(size.x<=1&&size.z<=1,'character fits within a tile');
assert.ok(Math.abs(box.min.y)<1e-6,'feet align with the player surface');
assert.ok(Math.abs(center.x)<.1&&Math.abs(center.z)<.1,'witch geometry is centered on player');
const player=new Group(),models=new Group();player.add(models);
let ready=false;const view=createModelView({layer:models,library,onChange:()=>ready=true});
const descriptor={id:'player',visual:prefab.visual,position:[0,0,0],dir:0};
assert.equal(view.update([descriptor]).size,0);
await new Promise(done=>setImmediate(done));assert.equal(ready,true);
assert.equal(view.update([descriptor]).has('player'),true);
player.position.set(3,2,4);player.rotation.y=-Math.PI/2;player.updateMatrixWorld(true);
const moved=new Box3().setFromObject(models).getCenter(new Vector3());
assert.ok(Math.abs(moved.x-3)<.1&&Math.abs(moved.z-4)<.1,'model follows player parent movement and facing');
view.update([]);assert.equal(models.children.length,0);
view.dispose();library.dispose();
console.log('PASS: protagonist FBX loads, fits a tile, rests on the surface and follows player transforms.');
